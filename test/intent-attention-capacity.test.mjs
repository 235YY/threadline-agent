// Synthetic data only; no model/provider/QQ access.
import test from 'node:test';
import assert from 'node:assert/strict';
import {ContinuityStore} from '../src/store.mjs';
import {ContinuitySession} from '../src/continuity-session.mjs';
import {attentionId,advanceAttention,emptyAttention,keepAttention,measureAttention,ATTENTION_CAPACITY_HINT} from '../src/attention.mjs';
import {intentPacket} from '../src/intent-protocol.mjs';
import {put,event,frame,ref} from './helpers.mjs';

function world(t,{maxForeground=8}={}){
  const store=new ContinuityStore(':memory:');t.after(()=>store.close());
  const session=new ContinuitySession({store,subjectId:'jingyang',attention:true,maxForeground});
  const [firstEvent,w]=put(store,'init',event('m1',{body:'合成输入：先看一下'}),frame());
  let currentEvent=ref(firstEvent),i=0;
  const base=()=>({currentEvent,workspace:ref(w),identity:'你是合成主体。',mind:true,unified:true,workbenchMaterials:true,workbenchFocus:true,workbenchRecovery:true,localLookupPolicy:{maxReads:2,maxHits:4},allowedActionTools:[],budgetBytes:131072,now:1800000000000});
  const s={store,session,
    prepare(extra={}){return session.prepare({...base(),intentProtocol:true,...extra});},
    prepareFull(extra={}){return session.prepare({...base(),...extra});},
    view(p){return JSON.parse(intentPacket(p).messages[1].content).view;},
    answer(p,intent,extra={}){const wire=intentPacket(p);const id='d'+(++i);return session.commit({packet:p,output:JSON.stringify({packetId:wire.packetId,...intent}),decisionId:id,requestId:id,allowedActionTools:[],...extra});},
    say(body){i++;const ev=put(store,'e'+i,event('m'+(i+1),{body})).at(-1);currentEvent={id:ev.id,revision:ev.revision};return s;}
  };
  return s;
}
const frameOf=s=>s.store.read(attentionId('jingyang'));

test('intent-v1 view exposes residences + used/max + W remove handle; explicit remove keeps state body/version',t=>{
  const s=world(t,{maxForeground:4});
  s.answer(s.prepare(),{decision:{type:'reply',text:'嗯'},states:[{kind:'feeling',text:'有点担心'}]});
  const beforeFrame=frameOf(s);
  assert.equal(beforeFrame.residences.length,1);
  const stateId=beforeFrame.residences[0].target.ref.id;
  assert.equal(beforeFrame.residences[0].id,`residence:${stateId}`,'autogenerated residence id');
  const stateBefore=s.store.read(stateId);

  s.say('下一件事');
  const p=s.prepare(),view=s.view(p),wire=intentPacket(p);
  assert.equal(Object.hasOwn(view.attention,'used'),false,'model view exposes no occupancy numbers');
  assert.equal(Object.hasOwn(view.attention,'max'),false);
  assert.equal(measureAttention(frameOf(s),4).used,1,'host-only measure retains used/max');
  assert.equal(measureAttention(frameOf(s),4).max,4);
  assert.equal(view.attention.residences.length,1);
  const row=view.attention.residences[0];
  assert.equal(row.handle,'W1');
  assert.equal(row.target,'state');
  assert.equal(row.delivery,'required');
  assert.deepEqual(row.purposes,['active-task']);
  assert.equal(wire.instruction.includes(ATTENTION_CAPACITY_HINT),false,'full sentence only when the desk is full');

  assert.throws(()=>s.answer(s.prepare(),{decision:{type:'wait'},remove:['S1']}),e=>e.code==='INTENT_HANDLE');

  s.answer(p,{decision:{type:'wait'},remove:['W1']});
  assert.equal(frameOf(s).residences.length,0);
  assert.deepEqual(s.store.read(stateId),stateBefore,'removing a residence never edits the state');
  const next=s.view(s.prepare());
  assert.equal(measureAttention(frameOf(s),4).used,0);
  assert.equal(next.attention.residences.length,0);
});

test('满桌 intent instruction 含 remove/W 语义；显式 remove 被解析并执行，无 used/max',t=>{
  const s=world(t,{maxForeground:1});
  s.answer(s.prepare(),{decision:{type:'reply',text:'嗯'},states:[{kind:'feeling',text:'担心'}]});
  const before=frameOf(s),stateId=before.residences[0].target.ref.id,stateBefore=s.store.read(stateId);
  assert.equal(before.residences.length,1,'desk is full at maxForeground=1');
  s.say('下一件事');
  const p=s.prepare(),wire=intentPacket(p),instruction=wire.messages[0].content,view=JSON.parse(wire.messages[1].content).view;
  assert.equal(instruction.includes(ATTENTION_CAPACITY_HINT),true,'capacity main hint stays the frozen sentence');
  assert.equal(instruction.includes('remove:["W1"]'),true,'instruction exposes remove/W semantics');
  assert.equal(instruction.includes('W 编号'),true);
  assert.equal(/used\s*\/\s*max/.test(instruction),false,'no numeric occupancy in instruction');
  assert.equal(instruction.includes('maxForeground'),false);
  assert.equal(view.attention.residences.length,1);
  assert.equal(view.attention.residences[0].handle,'W1','existing W numbering is preserved');
  s.answer(p,{decision:{type:'wait'},remove:['W1']});
  assert.equal(frameOf(s).residences.length,0,'explicit remove is parsed and executed');
  assert.deepEqual(s.store.read(stateId),stateBefore,'removing residence never edits the state');
});

test('未提供/非驻留的 W handle 被拒绝，桌位不变',t=>{
  const s=world(t,{maxForeground:1});
  s.answer(s.prepare(),{decision:{type:'reply',text:'嗯'},states:[{kind:'feeling',text:'担心'}]});
  s.say('下一件事');
  const p=s.prepare(),before=frameOf(s);
  assert.throws(()=>s.answer(p,{decision:{type:'wait'},remove:['W2']}),e=>e.code==='INTENT_HANDLE','only real provided W handles are accepted');
  assert.deepEqual(frameOf(s),before);
  assert.throws(()=>s.answer(p,{decision:{type:'wait'},remove:['S1']}),e=>e.code==='INTENT_HANDLE','a non-residence handle is not a W remove');
  assert.deepEqual(frameOf(s),before);
});

test('keep:false releases the autogenerated residence (no state delivery next turn)',t=>{
  const s=world(t);
  s.answer(s.prepare(),{decision:{type:'wait'},states:[{kind:'feeling',text:'担心'}]});
  const stateId=frameOf(s).residences[0].target.ref.id;
  s.say('好点没');
  const p=s.prepare(),view=s.view(p);
  const S=view.states[0].handle;
  s.answer(p,{decision:{type:'wait'},states:[{update:S,text:'好一些了',keep:false}]});
  assert.equal(frameOf(s).residences.length,0,'keep:false releases the only autogenerated residence');
  const state=s.store.read(stateId);
  assert.equal(state.body,'好一些了');
  assert.equal(state.status,'open');
  assert.equal(state.revision,2);
  s.say('然后呢');
  const v=s.view(s.prepare());
  assert.equal(measureAttention(frameOf(s),8).used,0);
  assert.ok(!(v.states??[]).some(x=>x.text==='好一些了'),'released state is not auto-delivered as foreground');
});

test('keep:false and W remove never touch a full-protocol residence with the same target',t=>{
  const s=world(t);
  s.answer(s.prepare(),{decision:{type:'wait'},states:[{kind:'feeling',text:'担心'}]});
  const auto=frameOf(s).residences[0];
  const stateId=auto.target.ref.id;
  // Full-protocol turn adds a subject-authored residence on the same state (self-directed).
  s.say('自选用途');
  const pf=s.prepareFull();
  s.session.commit({packet:pf,output:{packetId:pf.packetId,options:[{id:'a',kind:'wait',payload:{}}],selected:'a',summary:'合成自选驻留',used:[],
    continuity:{changes:[],residency:{add:[],remove:[]},expressionChoice:null,observationDisposition:'handled',
      attention:{...keepAttention(),residency:{upsert:[{id:'manual-res',target:{kind:'state',ref:{id:stateId,revision:1}},cue:'自选用途入口',
        purposes:[{kind:'self-directed',eventIds:[],questionId:null,appliesTo:null}]}],remove:[]}}}},
    decisionId:'full-manual',requestId:'full-manual'});
  assert.deepEqual(frameOf(s).residences.map(r=>r.id).sort(),['manual-res',`residence:${stateId}`]);
  s.say('再看');
  const p=s.prepare(),view=s.view(p);
  assert.equal(measureAttention(frameOf(s),8).used,2);
  const S=view.states[0].handle;
  s.answer(p,{decision:{type:'wait'},states:[{update:S,text:'好一点',keep:false}]});
  const after=frameOf(s);
  assert.deepEqual(after.residences.map(r=>r.id),['manual-res'],'keep:false only releases the autogenerated binding');
  assert.deepEqual(after.residences[0].purposes.map(p=>p.kind),['self-directed']);
  assert.equal(s.store.read(stateId).body,'好一点');
});

test('private foreground fallback reports the evicted residence ids through an observation hook',()=>{
  const state=id=>({type:'personal_state',id,revision:1,subject:'s',kind:'feeling',status:'open',body:'合成状态',scope:[],basis:null,recordedAt:1});
  const records=new Map([['s-old',state('s-old')],['s-new',state('s-new')]]);
  const old={id:'r-old',target:{kind:'state',ref:{id:'s-old',revision:1}},cue:'旧入口',purposes:[{kind:'self-directed',eventIds:[],questionId:null,appliesTo:null}]};
  const frame={...emptyAttention('s'),residences:[old]};
  const delta={processes:[],relations:[],questions:[],residency:{upsert:[{id:'r-new',target:{kind:'state',ref:{id:'s-new',revision:1}},cue:'新入口',
    purposes:[{kind:'self-directed',eventIds:[],questionId:null,appliesTo:null}]}],remove:[]}};
  const shared={read:id=>records.get(id)??null,at:2000,maxForeground:1,foregroundRecovery:true,
    observations:[],memoryRefs:[],processRefs:[],relationRefs:[],questionRefs:[],residenceIds:[],stateRefs:[{id:'s-new',revision:1}],changedStateIds:[]};
  const evicted=[];
  const next=advanceAttention(frame,delta,{...shared,onCapacityEviction:ids=>evicted.push(...ids)});
  assert.deepEqual(evicted,['r-old']);
  assert.deepEqual(next.residences.map(r=>r.id),['r-new']);
  const silent=advanceAttention(frame,delta,shared);
  assert.deepEqual(silent.residences.map(r=>r.id),['r-new'],'hook absence keeps existing fallback behavior');
});

test('process cap counts live processes only; completed/abandoned stay as tombstones',()=>{
  const proc=(i,status='completed')=>({id:'p'+i,revision:1,label:'p'+i,body:'过程',status,world:'actual',intervals:[],basis:[],recordedAt:1});
  const delta={processes:[{id:'new',expectedRevision:0,label:'new',body:'新过程',status:'active',world:'actual',intervals:[],basis:[]}],
    relations:[],residency:{upsert:[],remove:[]},questions:[]};
  const env={read:()=>null,at:1000,maxForeground:8,observations:[],memoryRefs:[],processRefs:[],relationRefs:[],questionRefs:[],residenceIds:[],stateRefs:[],changedStateIds:[]};
  const archived={...emptyAttention('s'),processes:Array.from({length:128},(_,i)=>proc(i))};
  const next=advanceAttention(archived,delta,env);
  assert.equal(next.processes.length,129);
  assert.equal(next.processes.find(p=>p.id==='p0').status,'completed','tombstones remain in frame for task evidence');
  const live={...emptyAttention('s'),processes:Array.from({length:128},(_,i)=>proc(i,'active'))};
  assert.throws(()=>advanceAttention(live,delta,env),e=>e.code==='ATTENTION_CAPACITY');
});
